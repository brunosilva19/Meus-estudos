num = int(input(''))
primeiro_termo = 0
segundo_termo = 1
count = 3
print(f'{primeiro_termo}, {segundo_termo}, ',end='')
while count <= num:
    terceiro_termo = primeiro_termo + segundo_termo
    print(f'{terceiro_termo}',end='')
    print(', ' if count < num else '',end='')
    primeiro_termo = segundo_termo
    segundo_termo = terceiro_termo
    count += 1